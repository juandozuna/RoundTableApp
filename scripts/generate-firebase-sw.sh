#!/usr/bin/env bash
# Generates firebase-config.js, the Firebase options for the web push service
# worker (web/firebase-messaging-sw.js). The worker cannot read --dart-define,
# so run this BEFORE `flutter build web` (default target: web/, which Flutter
# copies into build/web) or point it at an already built directory:
#
#   scripts/generate-firebase-sw.sh            # writes web/firebase-config.js
#   scripts/generate-firebase-sw.sh build/web  # writes build/web/firebase-config.js
#
# Reads FIREBASE_API_KEY, FIREBASE_WEB_APP_ID (or legacy FIREBASE_APP_ID),
# FIREBASE_MESSAGING_SENDER_ID, FIREBASE_PROJECT_ID and optionally
# FIREBASE_STORAGE_BUCKET from the environment. When they are incomplete it
# writes nothing and removes any stale file, so the worker only handles taps
# and the app runs without web push. The values identify the Firebase project
# and are not secret; the generated file is git-ignored.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target_dir="${1:-$repo_root/web}"
target="$target_dir/firebase-config.js"

app_id="${FIREBASE_WEB_APP_ID:-${FIREBASE_APP_ID:-}}"

if [[ -z "${FIREBASE_API_KEY:-}" || -z "$app_id" || -z "${FIREBASE_MESSAGING_SENDER_ID:-}" || -z "${FIREBASE_PROJECT_ID:-}" ]]; then
  rm -f "$target"
  echo "generate-firebase-sw: Firebase web config incomplete; web push service worker disabled." >&2
  exit 0
fi

# Values go into a JS string literal: reject anything that could break out.
for value in "$FIREBASE_API_KEY" "$app_id" "$FIREBASE_MESSAGING_SENDER_ID" "$FIREBASE_PROJECT_ID" "${FIREBASE_STORAGE_BUCKET:-}"; do
  if [[ "$value" =~ [^A-Za-z0-9:_.-] ]]; then
    echo "generate-firebase-sw: unexpected characters in a FIREBASE_* value." >&2
    exit 1
  fi
done

mkdir -p "$target_dir"
{
  echo "// Generated by scripts/generate-firebase-sw.sh. Do not edit or commit."
  echo "self.FIREBASE_CONFIG = {"
  echo "  apiKey: '$FIREBASE_API_KEY',"
  echo "  appId: '$app_id',"
  echo "  messagingSenderId: '$FIREBASE_MESSAGING_SENDER_ID',"
  echo "  projectId: '$FIREBASE_PROJECT_ID',"
  [[ -n "${FIREBASE_STORAGE_BUCKET:-}" ]] && echo "  storageBucket: '$FIREBASE_STORAGE_BUCKET',"
  echo "};"
} > "$target"
echo "generate-firebase-sw: wrote $target"
