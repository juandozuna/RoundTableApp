#!/usr/bin/env bash
# Release build of the Flutter web app for a HOSTED environment → build/web.
#
#   bash scripts/build-web.sh [--env-file FILE] [--no-pub-get]
#
# Reads deploy/hosted.env (template: deploy/hosted.env.example), never the local `.env`, and passes
# every `String.fromEnvironment` key of lib/core/config/app_config.dart as a --dart-define:
#   SUPABASE_URL, SUPABASE_ANON_KEY, POWERSYNC_URL, APP_ENV, DEV_AUTH (always false),
#   AUTH_METHODS (comma list of email,google,apple,facebook; default email),
#   ERROR_REPORT_URL, FIREBASE_API_KEY, FIREBASE_APP_ID, FIREBASE_MESSAGING_SENDER_ID,
#   FIREBASE_PROJECT_ID, FIREBASE_VAPID_KEY
# When the four required Firebase values are set it also writes build/web/firebase-config.js for the
# push service worker (web/firebase-messaging-sw.js). web/_headers, web/_redirects and web/404.html
# (Cloudflare Pages) are copied into build/web by Flutter.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=scripts/lib/hosted.sh
source "$here/lib/hosted.sh"

pub_get=true
while (($#)); do
  case "$1" in
    --env-file) hosted_env_file="${2:?--env-file needs a path}"; shift ;;
    --no-pub-get) pub_get=false ;;
    -h|--help) sed -n '2,/^set -euo/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) fail "Unknown option: $1 (see --help)" ;;
  esac
  shift
done

require_cmd flutter
load_hosted_env

[[ "${DEV_AUTH:-false}" == "false" ]] || fail "DEV_AUTH must not be enabled in a hosted build (it compiles in the email + password dev sign-in). Remove it from ${hosted_env_file#"$repo_root"/}."
require_https_url SUPABASE_URL
require_https_url POWERSYNC_URL
POWERSYNC_URL="${POWERSYNC_URL%/}"
case "$APP_ENV" in local|staging|production) ;; *) fail "APP_ENV must be local, staging or production (got '$APP_ENV')." ;; esac
AUTH_METHODS="${AUTH_METHODS:-email}"
AUTH_METHODS="${AUTH_METHODS// /}"
[[ "$AUTH_METHODS" =~ ^(email|google|apple|facebook)(,(email|google|apple|facebook))*$ ]] \
  || fail "AUTH_METHODS must be a comma-separated list of email, google, apple, facebook (got '$AUTH_METHODS')."
if [[ -n "${ERROR_REPORT_URL:-}" ]]; then require_https_url ERROR_REPORT_URL; fi

# The anon key is public; fetch it when absent and refuse anything that is not an anon/publishable key.
if [[ -z "${SUPABASE_ANON_KEY:-}" ]]; then
  if command -v supabase >/dev/null 2>&1 && command -v jq >/dev/null 2>&1; then
    info "SUPABASE_ANON_KEY is empty: asking the Supabase CLI"
    SUPABASE_ANON_KEY="$(supabase projects api-keys --project-ref "$SUPABASE_PROJECT_REF" -o json 2>/dev/null \
      | jq -r '[.[] | select(.name == "anon" or .type == "publishable")][0].api_key // empty' 2>/dev/null || true)"
  fi
  [[ -n "$SUPABASE_ANON_KEY" ]] || fail "SUPABASE_ANON_KEY is required (Dashboard → Project Settings → API → anon / publishable key)."
fi
case "$SUPABASE_ANON_KEY" in
  sb_secret_*) fail "SUPABASE_ANON_KEY holds a secret key. Use the anon / publishable key; secret keys must never reach a client." ;;
esac
if [[ "$SUPABASE_ANON_KEY" == eyJ* ]]; then
  payload="$(cut -d. -f2 <<<"$SUPABASE_ANON_KEY" | tr '_-' '/+')"
  payload="${payload}$(printf '%*s' $(((4 - ${#payload} % 4) % 4)) '' | tr ' ' '=')"
  if base64 -d <<<"$payload" 2>/dev/null | grep -q '"role" *: *"service_role"'; then
    fail "SUPABASE_ANON_KEY is the service-role key. Use the anon key; the service-role key bypasses RLS and must never be compiled into the app."
  fi
fi

defines=(
  "--dart-define=SUPABASE_URL=$SUPABASE_URL"
  "--dart-define=SUPABASE_ANON_KEY=$SUPABASE_ANON_KEY"
  "--dart-define=POWERSYNC_URL=$POWERSYNC_URL"
  "--dart-define=APP_ENV=$APP_ENV"
  "--dart-define=DEV_AUTH=false"
  "--dart-define=AUTH_METHODS=$AUTH_METHODS"
)
for name in ERROR_REPORT_URL FIREBASE_API_KEY FIREBASE_APP_ID FIREBASE_MESSAGING_SENDER_ID FIREBASE_PROJECT_ID FIREBASE_VAPID_KEY; do
  if [[ -n "${!name:-}" ]]; then defines+=("--dart-define=$name=${!name}"); fi
done

firebase_ready=false
if [[ -n "${FIREBASE_API_KEY:-}" && -n "${FIREBASE_APP_ID:-}" && -n "${FIREBASE_MESSAGING_SENDER_ID:-}" && -n "${FIREBASE_PROJECT_ID:-}" ]]; then
  firebase_ready=true
else
  warn "Firebase web config incomplete: the build has no web push (all of FIREBASE_API_KEY/APP_ID/MESSAGING_SENDER_ID/PROJECT_ID are needed)."
fi

info "flutter build web --release ($APP_ENV) → build/web"
cd "$repo_root"
if $pub_get; then flutter pub get >/dev/null; fi
flutter build web --release --base-href / "${defines[@]}"

if $firebase_ready; then
  for name in FIREBASE_API_KEY FIREBASE_APP_ID FIREBASE_MESSAGING_SENDER_ID FIREBASE_PROJECT_ID; do
    [[ "${!name}" =~ ^[A-Za-z0-9_:.-]+$ ]] || fail "$name contains characters that are not expected in a Firebase option."
  done
  cat >build/web/firebase-config.js <<JS
// Generated by scripts/build-web.sh from deploy/hosted.env. Firebase web options are not secret.
self.FIREBASE_CONFIG = {
  apiKey: '${FIREBASE_API_KEY}',
  appId: '${FIREBASE_APP_ID}',
  messagingSenderId: '${FIREBASE_MESSAGING_SENDER_ID}',
  projectId: '${FIREBASE_PROJECT_ID}',
};
JS
  ok "Wrote build/web/firebase-config.js"
fi

# Post-build sanity checks.
for file in index.html main.dart.js flutter_bootstrap.js sqlite3.wasm powersync_db.worker.js firebase-messaging-sw.js _headers _redirects 404.html; do
  [[ -f "build/web/$file" ]] || warn "build/web/$file is missing."
done
if ! grep -qF "$SUPABASE_URL" build/web/main.dart.js; then
  warn "The Supabase URL was not found in build/web/main.dart.js; check the --dart-define values."
fi
ok "Built build/web ($(du -sh build/web | cut -f1)) for $SUPABASE_URL, PowerSync $POWERSYNC_URL, DEV_AUTH=false, AUTH_METHODS=$AUTH_METHODS"
echo "   Deploy: see docs/deployment.md (Cloudflare Pages: npx wrangler pages deploy build/web --project-name <name>)"
